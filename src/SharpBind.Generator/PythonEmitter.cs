using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace SharpBind.Generator;

internal static class PythonEmitter
{
    /// <summary>
    /// Matches a surrogate pair of high and low unicodes.
    /// </summary>
    private static readonly Regex SurrogatePairRegex = new(@"\\u(D[89ABab][0-9A-Fa-f]{2})\\u(D[C-Fc-f][0-9A-Fa-f]{2})");

    /// <summary>
    /// Matches built-in type names ensuring the type name is matched as a whole word.
    /// </summary>
    private static readonly Regex BuiltinTypeRegex = new(@"\b(int|float|bool|str)\b");

    internal static string Literal(object? value)
    {
        if (value is null) return "None";
        if (value is bool boolean) return boolean ? "True" : "False";

        var literal = JsonSerializer.Serialize(value);

        if (value is string) return ReplaceSurrogatePairs(literal);
        if (value is float or double && !ContainsDecimalMarker(literal)) return literal + ".0";

        return literal;
    }

    /// <summary>
    /// Generates Python wrappers or type stubs for the exported classes.
    /// Qualifies built-in types in annotations (for example, <c>_builtins.int</c>)
    /// when an exported class has the same name.
    /// </summary>
    internal static string Emit(ExportClass[] classes, string schema, string module, bool stub)
    {
        var code = new StringBuilder();
        var shadowedNames = classes.Select(cls => cls.Name).ToHashSet(StringComparer.Ordinal);

        AppendHeader(code, classes, schema, stub);
        foreach (var cls in classes)
        {
            AppendClass(code, cls, module, stub, shadowedNames);
            code.AppendLine();
        }

        return code.ToString();
    }

    private static void AppendHeader(StringBuilder code, ExportClass[] classes, string schema, bool stub)
    {
        code.AppendLine("# Generated by SharpBind. Do not edit.");
        code.AppendLine("from __future__ import annotations");
        if (!stub) code.AppendLine("from . import _sharpbind as _sb");
        code.AppendLine("import builtins as _builtins");
        if (classes.SelectMany(cls => cls.Methods).Any(method =>
            method.Result?.Kind is LogicalTypeKind.Array or LogicalTypeKind.Tensor ||
            method.Arguments.Any(argument => argument.Type.Kind is LogicalTypeKind.Array or LogicalTypeKind.Tensor)))
        {
            code.AppendLine("import numpy as _np");
            code.AppendLine("import numpy.typing as _npt");
        }

        if (!stub)
        {
            code.AppendLine("import json as _json");
            code.AppendLine($"_provider = _sb.Library(_json.loads({JsonSerializer.Serialize(schema)}), __file__)");
        }

        var exports = string.Join(", ", classes.Select(cls => Literal(cls.Name)));
        code.AppendLine($"__all__ = [{exports}]");
        code.AppendLine();
    }

    private static void AppendClass(StringBuilder code, ExportClass cls, string module, bool stub, HashSet<string> shadowedNames)
    {
        var baseClass = cls.HasInstances && !stub ? "(_sb.NativeObject)" : "";

        code.AppendLine($"class {cls.Name}{baseClass}:");
        code.AppendLine($"    {Literal(cls.Documentation)}");
        code.AppendLine("    __slots__ = ()");

        if (!stub) AppendRuntimeClassMembers(code, cls, module);
        else if (cls.HasInstances) AppendLifetimeStubs(code, cls.Name);

        foreach (var method in cls.Methods)
            AppendMethod(code, method, stub, shadowedNames);
    }

    private static void AppendLifetimeStubs(StringBuilder code, string name)
    {
        code.AppendLine("    @property");
        code.AppendLine("    def closed(self) -> _builtins.bool: ...");
        code.AppendLine("    def close(self) -> None: ...");
        code.AppendLine($"    def __enter__(self) -> {name}: ...");
        code.AppendLine("    def __exit__(self, *_: _builtins.object) -> None: ...");
    }

    private static void AppendRuntimeClassMembers(StringBuilder code, ExportClass cls, string module)
    {
        code.AppendLine($"    __module__ = {Literal(module)}");

        if (!cls.HasInstances) return;

        code.AppendLine("    _provider = _provider");
        code.AppendLine($"    _release_entry = {Literal(cls.Prefix + "_release")}");
    }

    private static void AppendMethod(StringBuilder code, ExportMethod method, bool stub, HashSet<string> shadowedNames)
    {
        if (method.IsStatic) code.AppendLine("    @_builtins.staticmethod");

        var arguments = BuildArguments(method, shadowedNames);
        var returnType = method.IsConstructor
            ? "None"
            : TypeAnnotation(method.Result.Logical, isResult: true, shadowedNames);

        code.AppendLine($"    def {method.Name}({string.Join(", ", arguments)}) -> {returnType}:");
        code.AppendLine($"        {Literal(method.Documentation)}");

        if (stub)
        {
            code.AppendLine("        ...");
            return;
        }

        AppendMethodBody(code, method);
    }

    private static List<string> BuildArguments(ExportMethod method, HashSet<string> shadowedNames)
    {
        var arguments = new List<string>();
        if (!method.IsStatic) arguments.Add("self");

        arguments.AddRange(method.Arguments.Select(argument =>
        {
            var annotation = TypeAnnotation(argument.Type.Logical, isResult: false, shadowedNames);
            var defaultValue = argument.Optional ? $" = {Literal(argument.DefaultValue)}" : "";

            return $"{argument.Name}: {annotation}{defaultValue}";
        }));

        return arguments;
    }

    private static void AppendMethodBody(StringBuilder code, ExportMethod method)
    {
        var values = BuildArgumentTuple(method);
        var entryPoint = Literal(method.EntryPoint);

        if (method.IsConstructor) code.AppendLine($"        self._initialize({entryPoint}, {values})");
        else if (method.IsStatic) code.AppendLine($"        return _provider.invoke({entryPoint}, None, {values})");
        else code.AppendLine($"        return self._invoke({entryPoint}, {values})");
    }

    private static string BuildArgumentTuple(ExportMethod method)
    {
        var values = string.Join(", ", method.Arguments.Select(arg => arg.Name));
        var trailingComma = method.Arguments.Length == 1 ? "," : "";

        return $"({values}{trailingComma})";
    }

    private static string TypeAnnotation(LogicalType type, bool isResult, HashSet<string> shadowedNames)
    {
        var annotations = PythonTypes.TypeSignatures(type, isResult);
        MatchEvaluator evaluator = match => shadowedNames.Contains(match.Value) ? "_builtins." + match.Value : match.Value;

        return BuiltinTypeRegex.Replace(annotations, evaluator);
    }

    /// <summary>Encode C# UTF-16 string. Combines multi unit characters into one Unicode character. For example: \uD83D\uDE00 -> \U0001f60 (😀-emoji)</summary>
    private static string ReplaceSurrogatePairs(string literal)
    {
        return SurrogatePairRegex.Replace(literal, match =>
        {
            var high = (char)Convert.ToInt32(match.Groups[1].Value, 16);
            var low = (char)Convert.ToInt32(match.Groups[2].Value, 16);
            var codePoint = char.ConvertToUtf32(high, low);

            return @"\U" + codePoint.ToString("x8");
        });
    }

    private static bool ContainsDecimalMarker(string literal) =>
        literal.Contains('.') ||
        literal.Contains('E') ||
        literal.Contains('e');
}
