using System.Text.Json;
using System.Text.RegularExpressions;

namespace SharpBind.Generator;

internal enum PythonOutputKind
{
    Code,
    Stub
}

/// <summary>Renders one Python wrapper or type stub file.</summary>
internal class PythonEmitter(ExportClass[] classes, string schema, string module, PythonOutputKind outputKind)
{
    private readonly CodeBuilder code = new(CodeRules.Python);
    private readonly HashSet<string> shadowedNames = classes.Select(cls => cls.Name).ToHashSet(StringComparer.Ordinal);
    private bool emitted;

    private bool IsStub => outputKind == PythonOutputKind.Stub;

    /// <summary>
    /// Matches an escaped UTF-16 high/low surrogate pair.
    /// </summary>
    private static readonly Regex SurrogatePairRegex = new(@"\\u(D[89ABab][0-9A-Fa-f]{2})\\u(D[C-Fc-f][0-9A-Fa-f]{2})");

    /// <summary>
    /// Matches built-in type names ensuring the type name is matched as a whole word.
    /// </summary>
    private static readonly Regex BuiltinTypeRegex = new(@"\b(int|float|bool|str)\b");

    internal static string Literal(object? value)
    {
        if (value is null) return "None";
        if (value is bool boolean) return boolean ? "True" : "False";

        var literal = JsonSerializer.Serialize(value);

        if (value is string) return ReplaceSurrogatePairs(literal);
        if (value is float or double && !ContainsDecimalMarker(literal)) return literal + ".0";

        return literal;
    }

    /// <summary>
    /// Generates Python wrappers or type stubs for the exported classes.
    /// Qualifies built-in types in annotations (for example, <c>_builtins.int</c>)
    /// when an exported class has the same name.
    /// </summary>
    internal string Emit()
    {
        if (emitted) throw new InvalidOperationException("An emitter can only render one file.");
        emitted = true;

        EmitHeader();
        foreach (var cls in classes)
        {
            EmitClass(cls);
            code.BlankLine();
        }

        return code.ToString();
    }

    private void EmitHeader()
    {
        code.Line("# Generated by SharpBind. Do not edit.");
        code.Line("from __future__ import annotations");
        if (!IsStub) code.Line("from . import _sharpbind as _sb");
        code.Line("import builtins as _builtins");
        if (classes.SelectMany(cls => cls.Methods).Any(method =>
            method.Result?.Kind is LogicalTypeKind.Array or LogicalTypeKind.Tensor ||
            method.Arguments.Any(argument => argument.Type.Kind is LogicalTypeKind.Array or LogicalTypeKind.Tensor)))
        {
            code.Line("import numpy as _np");
            code.Line("import numpy.typing as _npt");
        }

        if (!IsStub)
        {
            code.Line("import json as _json");
            code.Line($"_provider = _sb.Library(_json.loads({JsonSerializer.Serialize(schema)}), __file__)");
        }

        var exports = string.Join(", ", classes.Select(cls => Literal(cls.Name)));
        code.Line($"__all__ = [{exports}]");
        code.BlankLine();
    }

    private void EmitClass(ExportClass cls)
    {
        var baseClass = cls.HasInstances && !IsStub ? "(_sb.NativeObject)" : "";

        using (code.ScopeStatement($"class {cls.Name}{baseClass}:"))
        {
            code.Line(Literal(cls.Documentation));
            code.Line("__slots__ = ()");

            if (!IsStub) EmitRuntimeClassMembers(cls);
            else if (cls.HasInstances) EmitLifetimeStubs(cls.Name);

            foreach (var method in cls.Methods)
                EmitMethod(method);
        }
    }

    private void EmitLifetimeStubs(string name)
    {
        code.Line("@property");
        code.Line("def closed(self) -> _builtins.bool: ...");
        code.Line("def close(self) -> None: ...");
        code.Line($"def __enter__(self) -> {name}: ...");
        code.Line("def __exit__(self, *_: _builtins.object) -> None: ...");
    }

    private void EmitRuntimeClassMembers(ExportClass cls)
    {
        code.Line($"__module__ = {Literal(module)}");

        if (!cls.HasInstances) return;

        code.Line("_provider = _provider");
        code.Line($"_release_entry = {Literal(cls.Prefix + "_release")}");
    }

    private void EmitMethod(ExportMethod method)
    {
        if (method.IsStatic) code.Line("@_builtins.staticmethod");

        var arguments = BuildArguments(method);
        var returnType = method.IsConstructor
            ? "None"
            : TypeAnnotation(method.Result.Logical, isResult: true);

        using (code.ScopeStatement($"def {method.Name}({string.Join(", ", arguments)}) -> {returnType}:"))
        {
            code.Line(Literal(method.Documentation));

            if (IsStub) code.Line("...");
            else EmitMethodBody(method);
        }
    }

    private List<string> BuildArguments(ExportMethod method)
    {
        var arguments = new List<string>();
        if (!method.IsStatic) arguments.Add("self");

        arguments.AddRange(method.Arguments.Select(argument =>
        {
            var annotation = TypeAnnotation(argument.Type.Logical, isResult: false);
            var defaultValue = argument.Optional ? $" = {Literal(argument.DefaultValue)}" : "";

            return $"{argument.Name}: {annotation}{defaultValue}";
        }));

        return arguments;
    }

    private void EmitMethodBody(ExportMethod method)
    {
        var values = BuildArgumentTuple(method);
        var entryPoint = Literal(method.EntryPoint);

        if (method.IsConstructor) code.Line($"self._initialize({entryPoint}, {values})");
        else if (method.IsStatic) code.Line($"return _provider.invoke({entryPoint}, None, {values})");
        else code.Line($"return self._invoke({entryPoint}, {values})");
    }

    private static string BuildArgumentTuple(ExportMethod method)
    {
        var values = string.Join(", ", method.Arguments.Select(arg => arg.Name));
        var trailingComma = method.Arguments.Length == 1 ? "," : "";

        return $"({values}{trailingComma})";
    }

    private string TypeAnnotation(LogicalType type, bool isResult)
    {
        var annotations = PythonTypes.TypeSignatures(type, isResult);
        MatchEvaluator evaluator = match => shadowedNames.Contains(match.Value) ? "_builtins." + match.Value : match.Value;

        return BuiltinTypeRegex.Replace(annotations, evaluator);
    }

    /// <summary>
    /// Replaces escaped UTF-16 surrogate pairs with Python Unicode escapes.
    /// For example, <c>\uD83D\uDE00</c> becomes <c>\U0001f600</c>.
    /// </summary>
    private static string ReplaceSurrogatePairs(string literal)
    {
        return SurrogatePairRegex.Replace(literal, match =>
        {
            var high = (char)Convert.ToInt32(match.Groups[1].Value, 16);
            var low = (char)Convert.ToInt32(match.Groups[2].Value, 16);
            var codePoint = char.ConvertToUtf32(high, low);

            return @"\U" + codePoint.ToString("x8");
        });
    }

    private static bool ContainsDecimalMarker(string literal) =>
        literal.Contains('.') ||
        literal.Contains('E') ||
        literal.Contains('e');
}
